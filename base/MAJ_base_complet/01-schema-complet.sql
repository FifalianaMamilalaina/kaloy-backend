CREATE TABLE IF NOT EXISTS "albums" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artist_id" BIGINT NOT NULL,
  "title" VARCHAR(150) NOT NULL,
  "cover_url" TEXT,
  "release_date" DATE,
