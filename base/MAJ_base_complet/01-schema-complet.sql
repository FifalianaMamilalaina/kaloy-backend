CREATE TABLE IF NOT EXISTS "songs" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artist_id" BIGINT NOT NULL,
  "album_id" BIGINT,
  "title" VARCHAR(150) NOT NULL,
  "duration_seconds" INT,
  "release_date" DATE,
  "language" VARCHAR(10) NOT NULL DEFAULT 'fr',
  "author_composer" VARCHAR(255),
  "musical_arranger" VARCHAR(255),
  "recording_location" VARCHAR(255),
  "recording_date" DATE,
  -- Nullable : une chanson déclarée avec seulement des paroles ou un solfa
  -- n'a pas de type de stockage audio.
  "storage_type_id" BIGINT,
  "audio_url" TEXT,
  -- Sprint 2 : clip vidéo (YouTube ou fichier local)
  "video_url" TEXT,
  -- Sprint 3 : paroles texte et karaoké synchronisé
  "lyrics" TEXT,
  "lyrics_sync_data" JSONB,
  -- Sprint 3 : solfa saisi en texte
  "solfa" TEXT,
  -- Sprint 3 : fichier karaoké vidéo (malgré le nom, contenu vidéo — cf. 07-eny-ampifitia.sql)
  "karaoke_audio_url" VARCHAR(255),
  -- Sprint 3 : piste playback (instrumental audio seul)
  "playback_url" VARCHAR(255),
  -- Sprint 3 : fichier solfa image ou PDF
  "solfa_url" VARCHAR(255),
  -- Sprint 7 : autorise ou interdit le téléchargement offline
  "is_downloadable" BOOLEAN NOT NULL DEFAULT TRUE,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("artist_id") REFERENCES "artists" ("id"),
  FOREIGN KEY ("album_id") REFERENCES "albums" ("id"),
  FOREIGN KEY ("storage_type_id") REFERENCES "audio_storage_types" ("id"),

  CONSTRAINT "ck_songs_duration"
    CHECK ("duration_seconds" IS NULL OR "duration_seconds" > 0)
);


CREATE TABLE IF NOT EXISTS "song_genres" (
