-- ============================================================
-- KALOY — SCHÉMA DU PÉRIMÈTRE PROJET (Sprints 0 à 10)
-- ============================================================
--
-- Ce fichier contient la structure des tables couvertes par les
-- fonctionnalités implémentées et validées dans le cadre du stage.
--
-- Sprints couverts :
--   Sprint 0  — Cadrage & conception base de données
--   Sprint 1  — Authentification mobile (connexion, rôles, Mon compte)
--   Sprint 2  — Lecteur audio et vidéo (clip)
--   Sprint 3  — Paroles (simple + karaoké), solfa, piste playback
--   Sprint 4  — File d'attente Up Next, historique horodaté, mode radio
--   Sprint 5  — Génération de playlist par critères
--   Sprint 6  — Fusion de playlists, lecture continue, playlists éditoriales
--   Sprint 7  — Mode offline : cache chiffré, téléchargement, quotas
--   Sprint 8  — Liste favoris, artistes suivis, désuivre
--   Sprint 9  — Historique des chansons, classement plus/moins écouté
--   Sprint 10 — Favoris chanson / album / artiste, lecture favoris
--
-- Tables NON incluses (hors périmètre) :
--   Événements / Concerts, Modération sociale, Notifications push,
--   Ingestion de contenu, Membres de groupes, Historique de recherche.
--
-- Usage :
--   createdb -U postgres kaloy_perimetre
--   psql -U postgres -d kaloy_perimetre -f 01-schema-projet.sql
--
-- Consolidé le 15/11/2026
-- ============================================================

-- ============================================================
-- SPRINT 0 — CONCEPTION BASE DE DONNÉES
-- Tables de référence (lookups sans dépendances)
-- ============================================================

CREATE TABLE IF NOT EXISTS "user_roles" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "user_statuses" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "audio_storage_types" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "artist_types" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "verification_channels" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "verification_statuses" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "verification_statuses_users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

-- Modes de lecture : AUDIO (Sprint 2) et VIDEO/clip (Sprint 2)
CREATE TABLE IF NOT EXISTS "play_modes" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

-- Visibilité des playlists : PRIVATE / PUBLIC (Sprints 5-6)
CREATE TABLE IF NOT EXISTS "playlist_visibilities" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

-- Cibles polymorphiques pour les favoris (Sprints 8-10).
CREATE TABLE IF NOT EXISTS "interaction_targets" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

-- ============================================================
-- SPRINT 1 — AUTHENTIFICATION MOBILE
-- ============================================================

CREATE TABLE IF NOT EXISTS "users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "email" VARCHAR(255) UNIQUE,
  "phone" VARCHAR(20) UNIQUE,
  "email_verified_at" TIMESTAMP,
  "phone_verified_at" TIMESTAMP,
  "password_hash" VARCHAR(255) NOT NULL,
  "role_id" BIGINT NOT NULL,
  "status_id" BIGINT NOT NULL,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),
  "updated_at" TIMESTAMP NOT NULL DEFAULT NOW(),
  "verification_status_user_id" BIGINT,

  FOREIGN KEY ("role_id") REFERENCES "user_roles" ("id"),
  FOREIGN KEY ("status_id") REFERENCES "user_statuses" ("id"),
  FOREIGN KEY ("verification_status_user_id") REFERENCES "verification_statuses_users" ("id"),

  CONSTRAINT "ck_users_contact" CHECK ("email" IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS "users_infos" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(255),
  "last_name" VARCHAR(255),
  "user_name" VARCHAR(255) UNIQUE,
  "id_user" BIGINT NOT NULL,
  "photo_url" VARCHAR(255),

  FOREIGN KEY ("id_user") REFERENCES "users" ("id")
);

CREATE TABLE IF NOT EXISTS "user_status_history" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT NOT NULL,
  "previous_status_id" BIGINT,
  "new_status_id" BIGINT NOT NULL,
  "reason" TEXT,
  "changed_by_user_id" BIGINT,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("user_id") REFERENCES "users" ("id"),
  FOREIGN KEY ("previous_status_id") REFERENCES "user_statuses" ("id"),
  FOREIGN KEY ("new_status_id") REFERENCES "user_statuses" ("id"),
  FOREIGN KEY ("changed_by_user_id") REFERENCES "users" ("id")
);

CREATE TABLE IF NOT EXISTS "verification_codes" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT NOT NULL,
  "channel_id" BIGINT NOT NULL,
  "destination" VARCHAR(255) NOT NULL,
  "code" VARCHAR(10) NOT NULL,
  "expires_at" TIMESTAMP NOT NULL,
  "consumed_at" TIMESTAMP,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("user_id") REFERENCES "users" ("id"),
  FOREIGN KEY ("channel_id") REFERENCES "verification_channels" ("id")
);

CREATE TABLE IF NOT EXISTS "clients" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT UNIQUE NOT NULL,

  FOREIGN KEY ("user_id") REFERENCES "users" ("id")
);

-- ============================================================
-- SPRINT 2 — LECTEUR AUDIO ET VIDÉO (CLIP)
-- ============================================================

CREATE TABLE IF NOT EXISTS "genres" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "artists" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT UNIQUE NOT NULL,
  "artist_type_id" BIGINT NOT NULL,
  "stage_name" VARCHAR(100) NOT NULL,
  "active_since_year" INT,
  "photo_url" TEXT,
  "bio" TEXT,
  "verification_status_id" BIGINT NOT NULL,
  "verified_at" TIMESTAMP,
  "is_certified" BOOLEAN NOT NULL DEFAULT FALSE,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("user_id") REFERENCES "users" ("id"),
  FOREIGN KEY ("artist_type_id") REFERENCES "artist_types" ("id"),
  FOREIGN KEY ("verification_status_id") REFERENCES "verification_statuses" ("id")
);

CREATE TABLE IF NOT EXISTS "albums" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artist_id" BIGINT NOT NULL,
  "title" VARCHAR(150) NOT NULL,
  "cover_url" TEXT,
  "release_date" DATE,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("artist_id") REFERENCES "artists" ("id")
);

CREATE TABLE IF NOT EXISTS "songs" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artist_id" BIGINT NOT NULL,
  "album_id" BIGINT,
  "title" VARCHAR(150) NOT NULL,
  "duration_seconds" INT,
  "release_date" DATE,
  "language" VARCHAR(10) NOT NULL,
  "author_composer" VARCHAR(255),
  "musical_arranger" VARCHAR(255),
  "recording_location" VARCHAR(255),
  "recording_date" DATE,
  "storage_type_id" BIGINT NOT NULL,
  "audio_url" VARCHAR(255) NOT NULL,
  "video_url" VARCHAR(255),
  "lyrics" TEXT,
  "lyrics_sync_data" VARCHAR(255),
  "solfa" TEXT,
  "karaoke_audio_url" VARCHAR(255),
  "playback_url" VARCHAR(255),
  "solfa_url" VARCHAR(255),
  "is_downloadable" BOOLEAN NOT NULL,
  "created_at" TIMESTAMP NOT NULL,

  FOREIGN KEY ("artist_id") REFERENCES "artists" ("id"),
  FOREIGN KEY ("album_id") REFERENCES "albums" ("id"),
  FOREIGN KEY ("storage_type_id") REFERENCES "audio_storage_types" ("id")
);

CREATE TABLE IF NOT EXISTS "song_genres" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "song_id" BIGINT NOT NULL,
  "genre_id" BIGINT NOT NULL,

  FOREIGN KEY ("song_id") REFERENCES "songs" ("id"),
  FOREIGN KEY ("genre_id") REFERENCES "genres" ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_song_genres_song_genre"
ON "song_genres" ("song_id", "genre_id");

-- ============================================================
-- SPRINT 4 — FILE D'ATTENTE UP NEXT / HISTORIQUE / MODE RADIO
-- ============================================================

CREATE TABLE IF NOT EXISTS "listening_history" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT NOT NULL,
  "song_id" BIGINT NOT NULL,
  "play_mode_id" BIGINT NOT NULL,
  "listened_at" TIMESTAMP NOT NULL DEFAULT NOW(),
  "completed" BOOLEAN,
  "duration_listened_seconds" INT,

  FOREIGN KEY ("user_id") REFERENCES "users" ("id"),
  FOREIGN KEY ("song_id") REFERENCES "songs" ("id"),
  FOREIGN KEY ("play_mode_id") REFERENCES "play_modes" ("id")
);

CREATE INDEX IF NOT EXISTS "idx_listening_history_user_date"
ON "listening_history" ("user_id", "listened_at" DESC);

CREATE INDEX IF NOT EXISTS "idx_listening_history_song"
ON "listening_history" ("song_id");

-- ============================================================
-- SPRINT 5 — GÉNÉRATION DE PLAYLIST PAR CRITÈRES
-- ============================================================

CREATE TABLE IF NOT EXISTS "playlists" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "owner_user_id" BIGINT NOT NULL,
  "name" VARCHAR(150) NOT NULL,
  "description" TEXT,
  "visibility_id" BIGINT NOT NULL,
  "share_token" VARCHAR(64) UNIQUE,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),
  "updated_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("owner_user_id") REFERENCES "users" ("id"),
  FOREIGN KEY ("visibility_id") REFERENCES "playlist_visibilities" ("id")
);

CREATE TABLE IF NOT EXISTS "playlist_songs" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "playlist_id" BIGINT NOT NULL,
  "song_id" BIGINT NOT NULL,
  "position" INT NOT NULL,
  "added_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("playlist_id") REFERENCES "playlists" ("id"),
  FOREIGN KEY ("song_id") REFERENCES "songs" ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_playlist_songs_playlist_song"
ON "playlist_songs" ("playlist_id", "song_id");

CREATE TABLE IF NOT EXISTS "playlist_generation_criteria" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "playlist_id" BIGINT NOT NULL,
  "target_duration_seconds" INT,
  "included_genres" TEXT[],
  "excluded_genres" TEXT[],
  "included_artist_ids" BIGINT[],
  "excluded_artist_ids" BIGINT[],
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("playlist_id") REFERENCES "playlists" ("id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "idx_generation_criteria_playlist_id"
ON "playlist_generation_criteria" ("playlist_id");

-- ============================================================
-- SPRINT 6 — FUSION, LECTURE CONTINUE, PLAYLISTS ÉDITORIALES
-- ============================================================

CREATE TABLE IF NOT EXISTS "playlist_fusions" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "result_playlist_id" BIGINT NOT NULL,
  "source_playlist_id" BIGINT NOT NULL,
  "fused_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("result_playlist_id") REFERENCES "playlists" ("id") ON DELETE CASCADE,
  FOREIGN KEY ("source_playlist_id") REFERENCES "playlists" ("id") ON DELETE CASCADE,

  UNIQUE ("result_playlist_id", "source_playlist_id")
);

CREATE INDEX IF NOT EXISTS "idx_fusions_result_playlist_id"
ON "playlist_fusions" ("result_playlist_id");

CREATE INDEX IF NOT EXISTS "idx_fusions_source_playlist_id"
ON "playlist_fusions" ("source_playlist_id");

CREATE TABLE IF NOT EXISTS "editorial_playlists" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artist_id" BIGINT NOT NULL,
  "title" VARCHAR(150) NOT NULL,
  "description" TEXT,
  "cover_url" TEXT,
  "is_featured" BOOLEAN NOT NULL DEFAULT FALSE,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("artist_id") REFERENCES "artists" ("id")
);

CREATE TABLE IF NOT EXISTS "editorial_playlist_songs" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "editorial_playlist_id" BIGINT NOT NULL,
  "song_id" BIGINT NOT NULL,
  "position" INT NOT NULL,

  FOREIGN KEY ("editorial_playlist_id") REFERENCES "editorial_playlists" ("id"),
  FOREIGN KEY ("song_id") REFERENCES "songs" ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_editorial_playlist_songs_playlist_song"
ON "editorial_playlist_songs" ("editorial_playlist_id", "song_id");

-- ============================================================
-- SPRINT 7 — MODE OFFLINE
-- ============================================================

CREATE TABLE IF NOT EXISTS "playlist_downloads" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT NOT NULL,
  "playlist_id" BIGINT NOT NULL,
  "downloaded_at" TIMESTAMP NOT NULL DEFAULT NOW(),
  "expires_at" TIMESTAMP NOT NULL,
  "is_active" BOOLEAN NOT NULL DEFAULT TRUE,

  FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE,
  FOREIGN KEY ("playlist_id") REFERENCES "playlists" ("id") ON DELETE CASCADE,

  UNIQUE ("user_id", "playlist_id")
);

CREATE INDEX IF NOT EXISTS "idx_downloads_user_id"
ON "playlist_downloads" ("user_id");

CREATE INDEX IF NOT EXISTS "idx_downloads_expires_at"
ON "playlist_downloads" ("expires_at");

CREATE OR REPLACE FUNCTION check_download_limit()
RETURNS TRIGGER AS $$
BEGIN
  IF (SELECT COUNT(*) FROM "playlist_downloads"
      WHERE "user_id" = NEW."user_id" AND "is_active" = TRUE) >= 10 THEN
    RAISE EXCEPTION 'Limite de 10 playlists téléchargées atteinte pour cet utilisateur';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_download_limit
BEFORE INSERT ON "playlist_downloads"
FOR EACH ROW
EXECUTE FUNCTION check_download_limit();

-- ============================================================
-- SPRINTS 8, 9, 10 — FAVORIS ET INTERACTIONS
-- ============================================================

CREATE TABLE IF NOT EXISTS "likes" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" BIGINT NOT NULL,
  "target_type_id" BIGINT NOT NULL,
  "target_id" BIGINT NOT NULL,
  "created_at" TIMESTAMP NOT NULL DEFAULT NOW(),

  FOREIGN KEY ("user_id") REFERENCES "users" ("id"),
  FOREIGN KEY ("target_type_id") REFERENCES "interaction_targets" ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_likes_user_target"
ON "likes" ("user_id", "target_type_id", "target_id");

-- ============================================================
-- COMMENTAIRES DOCUMENTAIRES
-- ============================================================

COMMENT ON TABLE "users" IS 'Un utilisateur doit avoir au moins un email ou un numéro de téléphone.';
COMMENT ON TABLE "songs" IS 'Table centrale du catalogue. Regroupe toutes les URLs media. is_downloadable contrôle le Sprint 7.';
COMMENT ON COLUMN "songs"."karaoke_audio_url" IS 'Contient une vidéo malgré le nom. Rendu par le lecteur vidéo mobile en mode KARAOKÉ.';
COMMENT ON TABLE "listening_history" IS 'Historique horodaté (Sprint 4). Sert au classement +/- (Sprint 9) et à la radio aléatoire.';
COMMENT ON TABLE "playlist_generation_criteria" IS 'Critères mémorisés pour la génération de playlist (Sprint 5). Jusqu à 3 propositions générées.';
COMMENT ON TABLE "playlist_fusions" IS 'Traçabilité des fusions (Sprint 6). Chaque ligne = une playlist source ayant contribué à result_playlist_id.';
COMMENT ON TABLE "playlist_downloads" IS 'Téléchargements offline (Sprint 7). Expire à 30 jours. Trigger : max 10 playlists actives par user.';
COMMENT ON TABLE "likes" IS 'Favoris polymorphiques (Sprints 8 & 10). target_type_id ∈ {SONG, ALBUM, ARTIST}.';

